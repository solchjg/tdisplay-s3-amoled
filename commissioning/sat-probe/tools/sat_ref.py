"""Satellite trial reference (Satellite data trial plan): the sample-data generator,
the expected hourly averages and ThingsBoard telemetry, and the raw-byte decoder.

Independent of the C packer, so the host tests can hold one against the other.
    python3 sat_ref.py synthetic OUT.csv   # writes the seeded synthetic set
    python3 sat_ref.py header OUT.h        # the sample days compiled into sat-probe
"""

import csv
import datetime
import math
import random
import struct
import sys

STEP = 3600
HOURS = 24
DAY = STEP * HOURS
BYTES = 57
BYTES_MINMAX = 61


def f16(x):
    """x rounded to float16 (round to nearest even), or None when it overflows."""
    try:
        return struct.unpack("<e", struct.pack("<e", float(x)))[0]
    except OverflowError:
        return None


def window_start(now):
    return now - now % STEP - DAY


def read_csv(path):
    """Rows of (t, value or None) from a t,value CSV; an empty value is no value."""
    with open(path, newline="") as f:
        return [(int(r["t"]), float(r["value"]) if r["value"] else None)
                for r in csv.DictReader(f)]


def write_csv(path, rows):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["t", "value"])
        for t, v in rows:
            w.writerow([t, "" if v is None else repr(v)])


def hourly(rows, now):
    """The 24 hours of the window ending before `now`: (t0, [avg or None] × 24),
    each average rounded to float16, None for no value or one float16 can't hold."""
    t0 = window_start(now)
    sums, counts = [0.0] * HOURS, [0] * HOURS
    for t, v in rows:
        if v is None or not t0 <= t < t0 + DAY:
            continue
        h = (t - t0) // STEP
        sums[h] += v
        counts[h] += 1
    return t0, [f16(s / c) if c else None for s, c in zip(sums, counts)]


def telemetry(rows, now, name, decimals=3):
    """What the route should post to ThingsBoard: §32.3's shape, the loop under `name`."""
    t0, avgs = hourly(rows, now)
    return [{"ts": (t0 + i * STEP) * 1000, "values": {name: round(v, decimals)}}
            for i, v in enumerate(avgs) if v is not None]


def decode_raw(b):
    """The raw little-endian bytes back into the fields of the note body."""
    if len(b) not in (BYTES, BYTES_MINMAX):
        raise ValueError(f"{len(b)} bytes")
    t0, step = struct.unpack_from("<IH", b, 0)
    miss = int.from_bytes(b[6:9], "little")
    vals = struct.unpack_from("<24e", b, 9)
    body = {"t0": t0, "step": step, "miss": miss}
    body.update({f"v{i + 1}": v for i, v in enumerate(vals)})
    if len(b) == BYTES_MINMAX:
        body["vmin"], body["vmax"] = struct.unpack_from("<2e", b, 57)
    return body


def synthetic(seed=20261105, start=1790812800, days=7, every=600):
    """A tank level that fills overnight and draws down by day, with noise,
    a reading every 10 minutes; about 2 % of readings fail, and one 2-hour outage."""
    rnd = random.Random(seed)
    rows = []
    outage = range(start + 3 * DAY + 10 * STEP, start + 3 * DAY + 12 * STEP)
    for t in range(start, start + days * DAY, every):
        hour = (t % DAY) / STEP
        level = 62.5 + 28.0 * math.sin(2 * math.pi * (hour - 9) / 24) + rnd.gauss(0, 0.8)
        v = None if (t in outage or rnd.random() < 0.02) else round(level, 3)
        rows.append((t, v))
    return rows


SYNTH_START = 1790812800  # synthetic()'s first reading, 2026-10-01 00:00 UTC


def sample_days():
    """The days sat-probe sends, as (name, now, rows): the synthetic 1, 2 and 4
    October 2026 (UTC; the 4th has the 2-hour outage) and an edge day, 8 October
    (hour 8 missing, hour 12 too big for float16, hour 20 a single reading)."""
    rows = synthetic()
    days = []
    for d in (1, 2, 4):  # the day before each send
        now = SYNTH_START + d * DAY + 120
        t0 = window_start(now)
        date = datetime.datetime.fromtimestamp(t0, datetime.timezone.utc).date()
        days.append((f"synthetic {date}", now, [r for r in rows if t0 <= r[0] < t0 + DAY]))
    t0 = SYNTH_START + 7 * DAY
    edge = [(t0 + h * STEP + k * 600, 70000.0 if h == 12 else 4.0 + h * 0.5)
            for h in range(HOURS) if h != 8 for k in range(1 if h == 20 else 6)]
    days.append(("edge 2026-10-08", t0 + DAY + 120, edge))
    return days


def write_header(path):
    out = ["// Generated by tools/sat_ref.py header: the sample days sat-probe sends.",
           "// Regenerate, never hand-edit; tests/host/test_sat_day.py checks it.",
           "#pragma once", "", "#include <math.h>", "#include <stdint.h>", "",
           "typedef struct { uint32_t t; double v; } sp_row_t;",
           "typedef struct { const char *name; uint32_t now; uint16_t n; const sp_row_t *rows; } sp_day_t;",
           ""]
    days = sample_days()
    for i, (_, _, rows) in enumerate(days):
        out.append(f"static const sp_row_t sp_rows_{i}[] = {{")
        out += [f"    {{{t}u, {'NAN' if v is None else repr(v)}}}," for t, v in rows]
        out += ["};", ""]
    out.append("static const sp_day_t sp_days[] = {")
    out += [f'    {{"{name}", {now}u, {len(rows)}, sp_rows_{i}}},'
            for i, (name, now, rows) in enumerate(days)]
    out += ["};", ""]
    with open(path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "synthetic":
        write_csv(sys.argv[2], synthetic())
    elif len(sys.argv) == 3 and sys.argv[1] == "header":
        write_header(sys.argv[2])
    else:
        sys.exit(__doc__)
